"""Pseudonymisation and masking of personal data and secrets (GDPR, Issue #53).

Two tools, both applied *before* anything is written to disk or sent outside:

- :meth:`Pseudonymizer.pseudonym` replaces an identifier (a user id, an e-mail address) by a
  keyed hash, HMAC-SHA256. The same person always gets the same pseudonym, so records can still
  be joined and counted, but nobody can go back to the person without the key. A plain hash
  (SHA-256 alone) would be reversible by trying every known e-mail address; the secret key
  prevents that attack.
- :meth:`Pseudonymizer.mask_text` hides, in free text, e-mail addresses, phone numbers, names
  that are known from the source system, and obvious secrets (passwords, API keys, tokens,
  private keys). Masked values are replaced by a fixed placeholder, never by a hash of the
  value, so the text cannot be used to guess the secret.

Limit (documented in docs/donnees/glpi-extraction-sql.md): a name that appears in free text
without being known from the source system cannot be recognised by rules; that needs a
named-entity model and is left as a future evolution.
"""

from __future__ import annotations

import hashlib
import hmac
import re
from collections import Counter
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path

from dotenv import dotenv_values

KEY_VARIABLE = "PSEUDONYMIZATION_KEY"
MIN_KEY_LENGTH = 32  # characters; 64 hex characters = 256 bits are generated by the procedure
PSEUDONYM_HEX_LENGTH = 16  # 64 bits: enough to avoid collisions among a few million people

EMAIL = "[EMAIL]"
PHONE = "[TELEPHONE]"
SECRET = "[SECRET]"
PERSON = "[PERSONNE]"
PRIVATE_KEY = "[CLE_PRIVEE]"


class PseudonymizationKeyError(Exception):
    """The key is missing or too short (the message never contains the key)."""


def load_key(env_file: str | Path = ".env") -> str:
    """Read ``PSEUDONYMIZATION_KEY`` from an env file."""
    path = Path(env_file)
    if not path.is_file():
        raise PseudonymizationKeyError(f"fichier d'environnement introuvable : {path}")
    key = dotenv_values(path).get(KEY_VARIABLE) or ""
    if len(key) < MIN_KEY_LENGTH:
        raise PseudonymizationKeyError(
            f"{KEY_VARIABLE} absente ou trop courte (minimum {MIN_KEY_LENGTH} caractères)"
        )
    return key


# Order matters: private keys, then labelled secrets, then loose tokens, e-mails, phones.
_PRIVATE_KEY_RE = re.compile(
    r"-----BEGIN [A-Z ]*PRIVATE KEY-----.*?(?:-----END [A-Z ]*PRIVATE KEY-----|\Z)", re.DOTALL
)
# "mot de passe actuel est X", "password: X", "code d'accès que j'utilise : X", "token=X"
_LABELLED_SECRET_RE = re.compile(
    r"(?P<label>\b(?:mot\s+de\s+passe|mdp|password|passwd|pwd|passphrase|code\s+d['’]acc[èe]s"
    r"|cl[ée](?:\s+d['’]api|\s+de\s+licence|\s+wifi)?|token|secret|api[_\s-]?key)\b"
    r"[^\n.:=]{0,40}?(?:\s*[:=]\s*|\s+(?:est|is)\s+))"
    r"(?P<value>[^\s,;]+)",
    re.IGNORECASE,
)
_LOOSE_SECRET_RES = (
    re.compile(r"\bFAKE-[A-Z]+-[A-Za-z0-9]+\b"),  # marker of the fictitious secrets of the project
    re.compile(r"\bsk-[A-Za-z0-9_-]{16,}\b"),  # API keys of several LLM providers
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),  # AWS access key id
    re.compile(r"\bgh[pousr]_[A-Za-z0-9]{20,}\b"),  # GitHub tokens
    re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}\b"),  # Slack tokens
    re.compile(r"\beyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\b"),  # JWT
    re.compile(r"\b[A-Fa-f0-9]{32,}\b"),  # long hexadecimal strings (hashes, keys)
)
_EMAIL_RE = re.compile(r"[A-Za-z0-9._%+'-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+")
# French numbers (0X XX XX XX XX, +33 X ..., 0033 ...) and generic international numbers.
_PHONE_RES = (
    re.compile(r"(?<![\w+])(?:(?:\+|00)33[\s.-]?\(?0?\)?|0)[1-9](?:[\s.-]?\d{2}){4}(?!\d)"),
    re.compile(r"(?<![\w+])\+\d{1,3}(?:[\s.-]?\d{2,4}){3,5}(?!\d)"),
)


@dataclass
class MaskResult:
    text: str
    counts: Counter = field(default_factory=Counter)


class Pseudonymizer:
    """Keyed pseudonyms and text masking. The key is never exposed (``repr`` hides it)."""

    def __init__(self, key: str) -> None:
        if len(key) < MIN_KEY_LENGTH:
            raise PseudonymizationKeyError(f"clé trop courte (minimum {MIN_KEY_LENGTH} caractères)")
        self._key = key.encode("utf-8")

    def __repr__(self) -> str:
        return "Pseudonymizer(key=<hidden>)"

    def pseudonym(self, value: str | int, kind: str = "person") -> str:
        """Stable pseudonym of an identifier, e.g. ``person-3f9a...``.

        ``kind`` separates the domains (a user id 7 and a ticket id 7 give different values).
        The value is trimmed and lowercased so that ``Anne@X.fr`` and ``anne@x.fr`` agree.
        """
        message = f"{kind}:{str(value).strip().lower()}".encode()
        digest = hmac.new(self._key, message, hashlib.sha256).hexdigest()
        return f"{kind}-{digest[:PSEUDONYM_HEX_LENGTH]}"

    def mask_text(self, text: str, known_names: Iterable[str] = ()) -> MaskResult:
        """Return the text without e-mails, phones, secrets and known names, with counts."""
        counts: Counter = Counter()

        def replace(pattern: re.Pattern[str], placeholder: str, name: str, source: str) -> str:
            masked, number = pattern.subn(placeholder, source)
            counts[name] += number
            return masked

        out = replace(_PRIVATE_KEY_RE, PRIVATE_KEY, "private_key", text)

        def labelled(match: re.Match[str]) -> str:
            counts["secret"] += 1
            return f"{match['label']}{SECRET}"

        out = _LABELLED_SECRET_RE.sub(labelled, out)
        for pattern in _LOOSE_SECRET_RES:
            out = replace(pattern, SECRET, "secret", out)
        out = replace(_EMAIL_RE, EMAIL, "email", out)
        for pattern in _PHONE_RES:
            out = replace(pattern, PHONE, "phone", out)
        for name in _name_variants(known_names):
            out = replace(
                re.compile(rf"(?<!\w){re.escape(name)}(?!\w)", re.IGNORECASE), PERSON, "name", out
            )
        return MaskResult(out, counts)


def _name_variants(names: Iterable[str]) -> list[str]:
    """Full names first, then each part of at least 3 letters; longest first."""
    variants: set[str] = set()
    for name in names:
        name = " ".join(name.split())
        if len(name) < 3:
            continue
        variants.add(name)
        variants.update(part for part in name.split() if len(part) >= 3)
    return sorted(variants, key=lambda v: (-len(v), v))
